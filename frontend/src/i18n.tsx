export function translateString(value: string, language: Language): string {
  if (language === "en" || !value) return value;
  const match = /^(\s*)([\s\S]*?)(\s*)$/.exec(value);
  if (!match) return value;
  const [, lead, core, trail] = match;
  if (!core || !/[A-Za-z]/.test(core)) return value;
  const direct = ES[core];
  if (direct) return lead + direct + trail;
  for (const rule of PATTERNS) {
    const m = rule.re.exec(core);
    if (m) return lead + rule.es(...m.slice(1)) + trail;
  }
  return value;
}

function translateNode(node: ReactNode, language: Language): ReactNode {
  if (typeof node === "string") return translateString(node, language);
  if (typeof node === "number" || typeof node === "boolean" || node == null) return node;
  if (Array.isArray(node)) return node.map((child) => translateNode(child, language));
  if (!isValidElement(node)) return node;

  const element = node as ReactElement<any>;
  const props = element.props || {};
  if (props.translate === "no" || props["data-no-translate"]) return node;

  const next: Record<string, unknown> = {};
  let changed = false;
  for (const [key, value] of Object.entries(props)) {
    if (key === "children" || key === "footer" || key === "actions" || key === "action" || key === "right" || key === "subtitle" || key === "title" || key === "hint" || key === "label" || key === "description" || key === "placeholder" || key === "aria-label" || key === "alt") {
      const translated = translateNode(value as ReactNode, language);
      next[key] = translated;
      if (translated !== value) changed = true;
    } else if (key === "options" && Array.isArray(value)) {
      const options = value.map((option: any) =>
        option && typeof option === "object" && typeof option.label === "string"
          ? { ...option, label: translateString(option.label, language) }
          : option,
      );
      next[key] = options;
      if (options.some((o: any, i: number) => o !== value[i])) changed = true;
    } else {
      next[key] = value;
    }
  }
  return changed ? cloneElement(element, next) : node;
}

/** Translates a rendered React subtree without changing component state. */
export function Localize({ children }: { children: ReactNode }) {
  const language = useStudio((s) => s.language);
  return <>{translateNode(children, language)}</>;
}

export function LanguageRoot({ children }: { children: ReactNode }) {
  const language = useStudio((s) => s.language);
  useEffect(() => {
    document.documentElement.lang = language === "es" ? "es" : "en";
  }, [language]);
  return <>{children}</>;
}
